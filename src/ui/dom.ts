/** Any handler: (e: KeyboardEvent) => void and friends are all assignable to (e: never) => unknown. */
type Handler = (e: never) => unknown;
type Attrs = Record<string, string | number | boolean | Handler | undefined | null>;
type Child = Node | string | false | null | undefined;

/** Creates an element: attributes (on* become listeners, false/null are skipped) and children. */
export function h<K extends keyof HTMLElementTagNameMap>(tag: K, attrs: Attrs = {}, ...children: Child[]): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs)) {
    if (value === false || value === null || value === undefined) continue;
    if (key.startsWith("on") && typeof value === "function") el.addEventListener(key.slice(2), value as EventListener);
    else if (key === "class") el.className = String(value);
    else el.setAttribute(key, value === true ? "" : String(value));
  }
  for (const child of children) if (child !== false && child !== null && child !== undefined) el.append(child);
  return el;
}

/** Sends a message to the worker; rejects with the worker's error text. */
export async function send<T>(msg: BgMessage): Promise<T> {
  const reply = (await chrome.runtime.sendMessage(msg)) as T | { error: string };
  // The worker answers a failure with exactly { error }; other replies may have an error field of their own.
  if (reply && typeof reply === "object" && Object.keys(reply).length === 1 && typeof (reply as { error?: unknown }).error === "string") {
    throw new Error((reply as { error: string }).error.replace(/^Error: /, ""));
  }
  return reply as T;
}

