/** A container's avatar: its emoji, or its first letter, on its colour. */
export function avatar(c: { name: string; emoji?: string; color: string } | null, opts: { large?: boolean; thisTab?: boolean } = {}): HTMLElement {
  const el = h("span", { class: `avatar${opts.large ? " lg" : ""}${c ? "" : " none"}`, "data-color": c?.color, "aria-hidden": "true" },
    c ? (c.emoji || c.name.slice(0, 1).toUpperCase()) : icon("globe"));
  if (opts.thisTab) el.append(h("span", { class: "this-tab-dot" }));
  return el;
}
